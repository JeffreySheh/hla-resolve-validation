#!/usr/bin/env python3
"""Grade HLA-Resolve calls against the reference typings, both references at once.

    python3 scripts/pipeline/5_test_against_truth.py results/audit.txt [more audit files...]

An input BAM is one sample x one library, named <sample>__<library>; its calls come from
the audit written by 4_audit_results.py. The reference for an input BAM is chosen by
sample: the Lai et al. key (eight genes, up to four fields) when the sample is
in it, otherwise the 1000 Genomes panel (HLA-A, -B, -C, -DQB1, -DRB1, two
fields).

Reads   data/manifest.tsv           input_bam -> sample, cohort, library, instrument
        data/lai_answer_key.tsv     Lai et al. reference typings
        data/kgp_answer_key.tsv     1000 Genomes panel, converted
        data/kgp_star_alleles.tsv   panel alleles flagged exome-only
Writes  results/calls.tsv           one row per input BAM: metadata, depth, call
                                    rate, concordance at each field, alleles
        results/misses.tsv          every discordant gene x input BAM with depth
        results/summary.txt         call rate and concordance tables per
                                    reference, a combined table, and a
                                    depth-gated table


MATCHING
--------
Alleles are compared field by field with zero padding (A*2:1 == A*02:01).
Pairing is unordered: every assignment of calls to reference alleles is tried
and the best-scoring one wins, so no call is credited against both reference
alleles. A reference ambiguity string (A*03:01/A*03:04) matches either option.


DENOMINATOR HANDLING
--------------------
An allele pair is graded independently at each field depth n. Whether a truth
allele contributes to the denominator depends on the TRUTH's resolution alone:

  truth shallower than n  ->  EXCLUDED from numerator and denominator.
        The reference cannot test that depth, so the call is neither credited
        nor penalised.
            n=4: call A*02:01:01:01 vs truth A*02:01:01  -> not evaluated

  truth resolved to n     ->  counted in the denominator. The call must itself
        resolve to n fields AND agree, or it scores as a miss. An
        under-resolved call is a failure to type, not a free pass.
            n=4: call A*02:01:01 vs truth A*02:01:01:01  -> miss
            n<=3: same pair                              -> hit


CALL RATE vs CONCORDANCE
------------------------
These answer different questions and are reported separately.

  Call rate is a property of hla_resolve alone and never consults the key: how
  often did the pipeline emit an allele at all? Every absent call counts
  against it.

  Concordance is accuracy among alleles actually called. A gene the pipeline
  did not type is a no-call, not an error, so it is left out of the
  concordance denominator entirely.

Every sample is graded. Low-depth samples need no special handling: falling
below the depth gate manifests as hla_resolve declining to emit calls, and that
is already counted -- against call rate, not against accuracy. Whatever such a
sample did call is graded on the same footing as everything else.

Nothing here reads the hand-graded columns of the results CSV. The report is a
function of the calls and the key alone, so it stays valid when the calls are
regenerated by a new hla_resolve version.
"""

import csv
import os
import re
import sys
from collections import defaultdict
from itertools import permutations

GENES = ["A", "B", "C", "DPA1", "DPB1", "DQA1", "DQB1", "DRB1"]

# (sample, gene, allele) triples dropped before grading: the Lai key marks one
# uncertain call with a trailing "#", which is not an IPD-IMGT/HLA designation.
EXCLUDED_ALLELES = {
    ("HG01358", "DRB1", "DRB1*04:92#"),
}

NO_CALL_PAT = re.compile(r"(?:^|\b)(?:no\s*call|na|none)$", re.IGNORECASE)


def is_called(allele):
    """True if the string is an actual allele designation rather than a blank
    or an explicit no-call."""
    return (isinstance(allele, str) and "*" in allele
            and not NO_CALL_PAT.search(allele.strip()))


def normalise(allele):
    """Strip an HLA- prefix and surrounding whitespace."""
    allele = allele.strip()
    return allele[4:] if allele.startswith("HLA-") else allele


def split_options(allele):
    """Split an ambiguity string ('A*01:01|A*01:02') into its options."""
    return [p.strip() for p in re.split(r"[|/]", allele) if p.strip()]


def truncate(allele, n):
    """Truncate to n fields, zero-padding each numeric field to two digits.
    Returns None when the allele is not resolved to n fields -- callers treat
    that as 'cannot match at this depth'."""
    if not is_called(allele):
        return None
    head, tail = normalise(allele).split("*", 1)
    fields = tail.split(":")
    if len(fields) < n:
        return None
    padded = []
    for f in fields[:n]:
        m = re.match(r"(\d+)(.*)", f)
        padded.append("%02d%s" % (int(m.group(1)), m.group(2)) if m else f)
    return "%s*%s" % (head, ":".join(padded))


def grade_gene(truth_alleles, call_alleles, n):
    """Grade one gene at n-field resolution.

    Returns (hits, denominator). Pairing is unordered: every assignment of
    calls to truth alleles is tried and the best-scoring one wins, so no call
    is ever credited against both truth alleles.

    A gene with no calls at all is a no-call and returns (0, 0) -- excluded
    from concordance, counted against call rate instead.
    """
    truth = [normalise(a) for a in truth_alleles if is_called(a)]
    calls = [normalise(a) for a in call_alleles if is_called(a)]
    if not calls:
        return 0, 0

    # Denominator is set by the truth's resolution alone.
    gradable = [i for i, a in enumerate(truth)
                if any(len(o.split("*", 1)[1].split(":")) >= n
                       for o in split_options(a))]
    if not gradable:
        return 0, 0

    # Pad so a half-typed gene still has slots to pair against; a None slot
    # can never match, i.e. it scores as a miss.
    slots = calls + [None] * max(0, len(truth) - len(calls))

    best = 0
    for perm in set(permutations(range(len(slots)), len(truth))):
        hits = 0
        for ti in gradable:
            call = slots[perm[ti]]
            if call is None:
                continue
            call_trunc = truncate(call, n)
            if call_trunc is None:
                continue  # call under-resolved at this depth -> miss
            options = {truncate(o, n) for o in split_options(truth[ti])}
            options.discard(None)
            if call_trunc in options:
                hits += 1
        best = max(best, hits)
    return best, len(gradable)


def load_key(path):
    """Headerless TSV: sample, then two alleles per gene in GENES order."""
    key = {}
    with open(path, newline="") as fh:
        for row in csv.reader(fh, delimiter="\t"):
            if not row or not row[0].strip():
                continue
            key[row[0].strip()] = {
                g: [row[1 + 2 * i].strip(), row[2 + 2 * i].strip()]
                for i, g in enumerate(GENES)}
    return key


def key_sample(entry):
    """Truth is keyed by sample; a plan-driven run is keyed by <sample>__<prep>."""
    return entry.split("__", 1)[0]


def apply_exclusions(key):
    dropped = []
    for sample, gene, allele in sorted(EXCLUDED_ALLELES):
        alleles = key.get(sample, {}).get(gene)
        if alleles and allele in alleles:
            alleles.remove(allele)
            dropped.append((sample, gene, allele))
    print("Excluded alleles (non-IMGT designations):")
    for sample, gene, allele in dropped:
        print("  %s  HLA-%s  %s" % (sample, gene, allele))
    if len(dropped) != len(EXCLUDED_ALLELES):
        print("  WARNING: some configured exclusions were not found in the key")
    return dropped


REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MANIFEST = os.path.join(REPO_ROOT, "data", "manifest.tsv")
LAI_KEY = os.path.join(REPO_ROOT, "data", "lai_answer_key.tsv")
KGP_KEY = os.path.join(REPO_ROOT, "data", "kgp_answer_key.tsv")
KGP_STAR = os.path.join(REPO_ROOT, "data", "kgp_star_alleles.tsv")
RESULTS = os.path.join(REPO_ROOT, "results")

TRUTHS = {
    "Lai": {"genes": GENES, "depths": [1, 2, 3, 4]},
    "1kGP": {"genes": ["A", "B", "C", "DQB1", "DRB1"], "depths": [1, 2]},
}
GATE_DEPTH = 10.0      # per-gene ARS depth for the gated table
DROPOUT_DEPTH = 20.0   # a miss at a gene below this is flagged as likely allelic dropout


# --------------------------------------------------------------------------
# input
# --------------------------------------------------------------------------

def read_block(path, name):
    rows, inside = [], False
    for line in open(path):
        line = line.rstrip("\n")
        if line == "=== %s ===" % name:
            inside = True
            continue
        if line == "=== END %s ===" % name:
            break
        if inside and line and not line.startswith("#"):
            rows.append(line.split("\t"))
    header, body = rows[0], rows[1:]
    return [dict(zip(header, r)) for r in body]


def load_audits(paths):
    """calls[entry][gene] = [a1, a2]; depth[entry] = coverage row; ars[entry][gene] = float."""
    calls, depth, ars = {}, {}, {}
    for p in paths:
        for r in read_block(p, "BLOCK1 ALLELE CALLS"):
            e = r.get("input_bam") or r.get("entry") or r["sample"]
            row = {g: [r["HLA-%s_1" % g], r["HLA-%s_2" % g]] for g in GENES}
            if not any(is_called(a) for g in GENES for a in row[g]):
                continue  # entry still running: audit found the directory but no calls
            calls[e] = row
        for r in read_block(p, "BLOCK2 COVERAGE SUMMARY"):
            depth[r.get("input_bam") or r.get("entry") or r["sample"]] = r
        for r in read_block(p, "BLOCK3 PER-GENE ARS DEPTH"):
            ars[r.get("input_bam") or r.get("entry") or r["sample"]] = {g: float(r[g]) if r.get(g, "") not in ("", "NA") else None for g in GENES}
    return calls, depth, ars


def load_manifest():
    meta = {}
    for r in csv.DictReader(open(MANIFEST), delimiter="\t"):
        m = meta.setdefault(r["input_bam"], {"sample": r["sample"], "cohort": r["cohort"],
                                          "library": r["library"], "instrument": r["instrument"],
                                          "files": []})
        m["files"].append(r["filename"])
    return meta


def load_star():
    star = set()
    if os.path.exists(KGP_STAR):
        for r in csv.DictReader(open(KGP_STAR), delimiter="\t"):
            star.add((r["sample"], r["gene"]))
    return star


# --------------------------------------------------------------------------
# grading
# --------------------------------------------------------------------------

def grade_entry(truth_row, call_row, genes, depths):
    """{(gene, n): (hits, denom)}"""
    out = {}
    for g in genes:
        for n in depths:
            out[(g, n)] = grade_gene(truth_row[g], call_row[g], n)
    return out


def fmt(h, d):
    return "%d/%d" % (h, d) if d else ""


def pct(h, d):
    return "%6.2f%%" % (100.0 * h / d) if d else "     --"


def table(title, genes, depths, cell):
    """cell(gene, n) -> (hits, denom). Returns the printed block as a string."""
    lines = [title, "  %6s" % "" + "".join("%9s" % g for g in genes) + "%20s" % "TOTAL"]
    for n in depths:
        h_t = d_t = 0
        row = "  %4df  " % n
        for g in genes:
            h, d = cell(g, n)
            h_t += h
            d_t += d
            row += "%9s" % fmt(h, d)
        row += "%12s = %s" % (fmt(h_t, d_t), pct(h_t, d_t).strip())
        lines.append(row)
    return "\n".join(lines)


def main(paths):
    calls, depth, ars = load_audits(paths)
    meta = load_manifest()
    lai = load_key(LAI_KEY)
    kgp = load_key(KGP_KEY)
    star = load_star()
    apply_exclusions(lai)

    os.makedirs(RESULTS, exist_ok=True)
    # only entries the manifest defines; a typed directory the plan later
    # dropped (a thin library superseded by a deeper one) is left out
    not_planned = sorted(e for e in calls if e not in meta)
    entries = sorted(e for e in calls if e in meta)
    truth_of, graded, skipped = {}, {}, []
    for e in entries:
        s = key_sample(e)
        if s in lai:
            truth_of[e] = ("Lai", lai[s])
        elif s in kgp:
            truth_of[e] = ("1kGP", kgp[s])
        else:
            skipped.append(e)
            continue
        name, key = truth_of[e]
        graded[e] = grade_entry(key, calls[e], TRUTHS[name]["genes"], TRUTHS[name]["depths"])

    # ---- calls.tsv --------------------------------------------------------
    cols = (["input_bam", "sample", "cohort", "library", "instrument", "truth", "n_files",
             "mean_gene_depth", "mean_ARS_depth", "min_ARS_depth"]
            + ["ARS_%s" % g for g in GENES]
            + ["genes_typed", "alleles_called", "1f", "2f", "3f", "4f"]
            + ["HLA-%s_%d" % (g, i) for g in GENES for i in (1, 2)])
    with open(os.path.join(RESULTS, "calls.tsv"), "w", newline="") as fh:
        w = csv.writer(fh, delimiter="\t")
        w.writerow(cols)
        for e in entries:
            m = meta.get(e, {})
            name = truth_of.get(e, ("", None))[0]
            d = depth.get(e, {})
            a = ars.get(e, {})
            typed = sum(1 for g in GENES if any(is_called(x) for x in calls[e][g]))
            called = sum(1 for g in GENES for x in calls[e][g] if is_called(x))
            gr = graded.get(e, {})
            per_field = []
            for n in (1, 2, 3, 4):
                h = sum(v[0] for (g, k), v in gr.items() if k == n)
                dd = sum(v[1] for (g, k), v in gr.items() if k == n)
                per_field.append(fmt(h, dd))
            w.writerow([e, key_sample(e), m.get("cohort", ""), m.get("library", ""), m.get("instrument", ""),
                        name, len(m.get("files", [])),
                        d.get("mean_gene_depth", ""), d.get("mean_ARS_depth", ""), d.get("min_ARS_depth", ""),
                        *["%.1f" % a[g] if a.get(g) is not None else "" for g in GENES],
                        "%d/8" % typed, "%d/16" % called, *per_field,
                        *[calls[e][g][i] for g in GENES for i in (0, 1)]])

    # ---- misses.tsv -------------------------------------------------------
    n_miss = 0
    with open(os.path.join(RESULTS, "misses.tsv"), "w", newline="") as fh:
        w = csv.writer(fh, delimiter="\t")
        w.writerow(["input_bam", "sample", "truth", "gene", "field", "hits", "denom", "ARS_depth",
                    "call_1", "call_2", "truth_1", "truth_2", "note"])
        for e in entries:
            if e not in graded:
                continue
            name, key = truth_of[e]
            for g in TRUTHS[name]["genes"]:
                # report the shallowest field at which the gene first misses
                for n in TRUTHS[name]["depths"]:
                    h, d = graded[e][(g, n)]
                    if d and h < d:
                        dep = ars.get(e, {}).get(g)
                        notes = []
                        if dep is not None and dep < DROPOUT_DEPTH:
                            notes.append("ARS depth under %gx" % DROPOUT_DEPTH)
                        if name == "1kGP" and (key_sample(e), g) in star:
                            notes.append("panel allele flagged exome-only (*)")
                        w.writerow([e, key_sample(e), name, g, n, h, d,
                                    "%.1f" % dep if dep is not None else "",
                                    *calls[e][g], *key[g], "; ".join(notes)])
                        n_miss += 1
                        break

    # ---- summary.txt ------------------------------------------------------
    out = []
    out.append("hla_resolve WGS validation: %d entries graded from %d audit file(s)" % (len(graded), len(paths)))
    if skipped:
        out.append("no reference typing for %d entries (not graded): %s" % (len(skipped), " ".join(skipped)))
    if not_planned:
        out.append("typed but not in the manifest (ignored): %s" % " ".join(not_planned))
    for name in ("Lai", "1kGP"):
        es = [e for e in entries if truth_of.get(e, ("",))[0] == name]
        if not es:
            continue
        genes, depths = TRUTHS[name]["genes"], TRUTHS[name]["depths"]
        samples = {key_sample(e) for e in es}
        out.append("")
        out.append("== %s truth: %d entries, %d samples ==" % (name, len(es), len(samples)))
        called = sum(1 for e in es for g in genes for x in calls[e][g] if is_called(x))
        expected = 2 * len(genes) * len(es)
        untyped = [(e, g) for e in es for g in genes if not any(is_called(x) for x in calls[e][g])]
        out.append("call rate: %d/%d = %.2f%% (%d gene x input BAM untyped)" % (called, expected, 100.0 * called / expected, len(untyped)))
        for e, g in untyped:
            dep = ars.get(e, {}).get(g)
            out.append("  %-45s HLA-%-5s ARS %s" % (e, g, "%.1fx" % dep if dep is not None else "NA"))
        cell = lambda g, n, es=es: (sum(graded[e][(g, n)][0] for e in es), sum(graded[e][(g, n)][1] for e in es))
        out.append(table("concordance among called alleles:", genes, depths, cell))
        if name == "1kGP":
            gated = lambda g, n, es=es: (
                sum(graded[e][(g, n)][0] for e in es if (ars.get(e, {}).get(g) or 0) >= GATE_DEPTH),
                sum(graded[e][(g, n)][1] for e in es if (ars.get(e, {}).get(g) or 0) >= GATE_DEPTH))
            out.append(table("concordance, genes with ARS depth >= %gx only:" % GATE_DEPTH, genes, depths, gated))
        deps = sorted(float(depth[e]["mean_gene_depth"]) for e in es if depth.get(e, {}).get("mean_gene_depth"))
        if deps:
            out.append("mean HLA gene depth: mean %.1fx, median %.1fx, range %.1f-%.1fx" % (
                sum(deps) / len(deps), deps[len(deps) // 2], deps[0], deps[-1]))
    es = [e for e in entries if e in graded]
    out.append("")
    out.append("== both references pooled, %d input BAMs ==" % len(es))
    for n in (1, 2, 3, 4):
        h = sum(v[0] for e in es for (g, k), v in graded[e].items() if k == n)
        d = sum(v[1] for e in es for (g, k), v in graded[e].items() if k == n)
        out.append("  %df  %s = %s" % (n, fmt(h, d), pct(h, d).strip()))
    out.append("")
    out.append("misses: %d gene x input BAM -> results/misses.tsv" % n_miss)
    text = "\n".join(out) + "\n"
    open(os.path.join(RESULTS, "summary.txt"), "w").write(text)
    print(text)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
